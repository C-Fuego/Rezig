#!/usr/bin/env python3
"""Generate the tiny test fonts used by zfiglet's unit tests.

The fonts are deliberately boring: every printable character is drawn as the
character itself in a 3x3 cell, with the FIGlet endmark "@" after the content.
That is enough to exercise the parser (102 mandatory glyphs, endmark stripping,
print direction, layout), the layout engine (full width, wrapping) and the
TOIlet-style .tlf path (UTF-8 glyphs plus code-tagged characters).

Run from the project root:
    python3 tools/gen_tiny_font.py
"""

import gzip
import pathlib
import zipfile

HEIGHT = 3
BASELINE = 2
MAX_LEN = 4
OLD_LAYOUT = -1          # full width by default
FULL_LAYOUT = 0
COMMENT_LINES = 1
HARDBLANK = "$"

GERMAN = [196, 214, 220, 228, 246, 252, 223]
ORDER = list(range(32, 127)) + GERMAN


def glyph(ch: str) -> list[str]:
    """Three rows of three columns; endmarks are added by the caller."""
    if ch == " ":
        return [HARDBLANK * 3] * HEIGHT
    return ["   ", f" {ch} ", "   "]


def render_block(ch: str, last_double: bool = False) -> list[str]:
    rows = glyph(ch)
    out = []
    for i, row in enumerate(rows):
        end = "@@" if last_double and i == HEIGHT - 1 else "@"
        out.append(row + end)
    return out


def flf() -> str:
    lines = [
        f"flf2a{HARDBLANK} {HEIGHT} {BASELINE} {MAX_LEN} {OLD_LAYOUT} "
        f"{COMMENT_LINES} 0 {FULL_LAYOUT} 0",
        "tiny.flf - generated by tools/gen_tiny_font.py for zfiglet tests",
    ]
    for code in ORDER:
        ch = chr(code) if code < 127 else "?"
        lines.extend(render_block(ch, last_double=True))
    return "\n".join(lines) + "\n"


def tlf() -> str:
    # Two code-tagged characters: 中 (U+4E2D) and 文 (U+6587).
    lines = [
        f"tlf2a{HARDBLANK} {HEIGHT} {BASELINE} {MAX_LEN} {OLD_LAYOUT} "
        f"{COMMENT_LINES} 0 {FULL_LAYOUT} 2",
        "tiny.tlf - generated by tools/gen_tiny_font.py for zfiglet tests",
    ]
    for code in ORDER:
        ch = chr(code) if code < 127 else "?"
        lines.extend(render_block(ch, last_double=True))
    for ch in "中文":
        lines.append(f"0x{ord(ch):04X}")
        lines.extend(render_block(ch, last_double=True))
    return "\n".join(lines) + "\n"


def main() -> None:
    root = pathlib.Path(__file__).resolve().parent.parent
    data = root / "src" / "testdata"
    data.mkdir(exist_ok=True)

    flf_bytes = flf().encode()
    (data / "tiny.flf").write_text(flf(), encoding="utf-8")
    (data / "tiny.tlf").write_text(tlf(), encoding="utf-8")

    # Deterministic compressed fixtures used by the zlib tests.
    (data / "tiny.flf.gz").write_bytes(
        gzip.compress(flf_bytes, compresslevel=9, mtime=0)
    )
    for name, method in (
        ("tiny.flf.zip", zipfile.ZIP_DEFLATED),
        ("tiny_stored.flf.zip", zipfile.ZIP_STORED),
    ):
        info = zipfile.ZipInfo("tiny.flf", date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = method
        with zipfile.ZipFile(data / name, "w") as archive:
            archive.writestr(info, flf_bytes)


if __name__ == "__main__":
    main()
